import type { ParamSpec } from "@/lib/palette/component-catalog";

export type LadderCategory =
  | "Contatos e Bordas"
  | "Bobinas e Retenções"
  | "Temporizadores"
  | "Contadores"
  | "Comparadores"
  | "Matemática"
  | "Lógica Booleana"
  | "Transferência e Dados"
  | "Blocos de Fabricantes";

export interface LadderElement {
  id: string;
  type: string;
  category: LadderCategory;
  label: string;
  mnemonic: string;
  description: string;
  dataType?: "BOOL" | "INT" | "DINT" | "REAL" | "TIME" | "STRING";
  allenBradley?: string;
  siemens?: string;
  params: Record<string, ParamSpec>;
  inputs: number;
  outputs: number;
  symbol: string;
  /** Se true, suportado nativamente no grid estrutural e executado pelo scan-core. */
  supported: boolean;
  statusNote?: string;
  isFavorite?: boolean;
}

const param = (
  key: string,
  label: string,
  defaultValue: number | boolean | string,
  unit?: string,
): ParamSpec => ({
  key,
  label,
  type: typeof defaultValue === "number" ? (unit === "ms" ? "time" : "number") : "select",
  defaultValue,
  unit,
  min: typeof defaultValue === "number" ? 0 : undefined,
});

const element = (
  id: string,
  category: LadderCategory,
  label: string,
  mnemonic: string,
  symbol: string,
  description: string,
  dataType: "BOOL" | "INT" | "DINT" | "REAL" | "TIME" | "STRING" = "BOOL",
  params: Record<string, ParamSpec> = {},
  allenBradley?: string,
  siemens?: string,
  supported: boolean = true,
  statusNote?: string,
  isFavorite: boolean = false,
): LadderElement => ({
  id,
  type: id,
  category,
  label,
  mnemonic,
  description,
  dataType,
  allenBradley,
  siemens,
  params,
  inputs: 1,
  outputs: 1,
  symbol,
  supported,
  statusNote,
  isFavorite,
});

